def esc(s):
    return s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")


def main():
    root = os.path.join(os.path.dirname(__file__), "..", "Resources", "Localization")
    en = T["en"]
    assert set(en) == set(KEYS), set(en) ^ set(KEYS)
    for lang, table in T.items():
        extra = set(table) - set(KEYS)
        assert not extra, (lang, extra)
        missing = [k for k in KEYS if k not in table]
        if missing:
            print(f"{lang}: {len(missing)} missing -> English fallback")
        d = os.path.join(root, f"{lang}.lproj")
        os.makedirs(d, exist_ok=True)
        with open(os.path.join(d, "Localizable.strings"), "w", encoding="utf-8") as f:
            f.write("/* Generated by scripts/translations.py — edit that file, not this one. */\n\n")
            for k in KEYS:
                f.write(f'"{k}" = "{esc(table.get(k, en[k]))}";\n')
    print(f"wrote {len(T)} languages")


if __name__ == "__main__":
    main()
